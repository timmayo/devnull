"""Generate the command tree and reference from data/commands.yaml.

    python tools/gen_docs.py            writes docs/command_tree.txt and docs/command_reference.docx
    python tools/gen_docs.py --out DIR  write somewhere else

The .docx needs python-docx:  python -m pip install python-docx   (the .txt needs nothing).
Edit data/commands.yaml, run this, and the documents follow. Never edit the generated files.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from devnull.core.sim import load_rules  # noqa: E402

LAB = {"evidence": "evidence", "os": "Linux installed", "skills": "skill", "trust": "trust", "terms": "agreement terms",
       "laptop": "working laptop", "cash": "cash", "heat": "heat", "legibility": "legibility", "burnout": "burnout",
       "verified": "verified evidence", "auth": "authenticity", "cred": "credibility", "case": "case strength",
       "case_file": "case file against you", "filed": "case filed", "opinion": "public opinion",
       "lead_linux": "Linux lead", "lead_store": "store lead", "lead_npc": "developer lead", "people_n": "people known",
       "darknet": "darknet access", "press_trust": "press trust", "techie_trust": "developer trust",
       "meetings": "meetings", "leverage": "leverage", "public_concern": "public concern", "market": "market"}


def lab(k: str) -> str:
    return k[3:].replace("_", " ") + " skill" if k.startswith("sk_") else LAB.get(k, k.replace("_", " "))


def need(d: object) -> str:
    if not isinstance(d, dict) or not d:
        return ""
    out = []
    for k, v in d.items():
        out.append(f"${v}" if k == "cash" else lab(k) if v == 1 and k in ("os", "laptop") else f"{lab(k)} {v}+")
    return ", ".join(out)


def when(c: dict) -> str:
    u = c.get("unlock")
    return "admin only" if u == "admin" else need(u) or "Day 1"


def cost_text(c: dict) -> str:
    h = f"{c['hours']}h" if c.get("hours") else "free"
    return h + (f" + ${c['cost']}" if c.get("cost") else "")


def make_txt(cm: dict, path: Path) -> None:
    """A command with a `parent` is drawn under that parent, whatever its own group."""
    cmds = cm["commands"]
    kids: dict[str, list[str]] = {}
    for k, c in cmds.items():
        if c.get("parent"):
            kids.setdefault(c["parent"], []).append(k)
    L = ["/dev/null COMMAND TREE (generated from data/commands.yaml; do not edit this file)", "", "/dev/null"]

    def line(k: str, prefix: str, last: bool) -> None:
        c = cmds[k]
        L.append(f"{prefix}{'└── ' if last else '├── '}{c['usage']:<{max(8, 58 - len(prefix))}} {cost_text(c):<10} {when(c):<30} {c['help']}")
        sub = kids.get(k, [])
        for i, ch in enumerate(sub):
            line(ch, prefix + ("    " if last else "│   "), i == len(sub) - 1)

    groups = list(cm["groups"])
    for gi, g in enumerate(groups):
        glast = gi == len(groups) - 1
        meta = cm["groups"][g]
        L.append(("└── " if glast else "├── ") + f"{meta['title']}  ({meta['note']})")
        roots = [k for k, c in cmds.items() if c["group"] == g and not c.get("parent")]
        for i, k in enumerate(roots):
            line(k, "    " if glast else "│   ", i == len(roots) - 1)
    path.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\r\n")


def eff(e: dict | None) -> str:
    up, down = [], []
    for k, v in (e or {}).items():
        if k == "skill_xp":
            continue
        if "set" in v:
            up.append(lab(k))
            continue
        b = v.get("bias", 0)
        if b > 0 or (b == 0 and v.get("terms")):
            up.append(lab(k))
        elif b < 0:
            down.append(lab(k))
    return "; ".join(x for x in ((("Up: " + ", ".join(up)) if up else ""), (("Down: " + ", ".join(down)) if down else "")) if x)


def make_docx(rules: dict, path: Path) -> None:
    from docx import Document
    from docx.enum.section import WD_ORIENT
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Inches, Pt, RGBColor
    cm = rules["commands"]
    d = Document()
    s = d.sections[0]
    s.orientation = WD_ORIENT.LANDSCAPE
    s.page_width, s.page_height = s.page_height, s.page_width
    for m in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(s, m, Inches(0.6))
    d.styles["Normal"].font.name = "Calibri"
    d.styles["Normal"].font.size = Pt(10)

    def table(head: list[str], rows: list[list[str]], widths: list[float]) -> None:
        t = d.add_table(rows=1, cols=len(head))
        t.style = "Table Grid"
        t.autofit = False
        lay = OxmlElement("w:tblLayout")
        lay.set(qn("w:type"), "fixed")
        t._tbl.tblPr.append(lay)
        for i, h in enumerate(head):
            c = t.rows[0].cells[i]
            c.text = ""
            r = c.paragraphs[0].add_run(h)
            r.bold = True
            r.font.size = Pt(9)
            r.font.color.rgb = RGBColor(255, 255, 255)
            sh = OxmlElement("w:shd")
            sh.set(qn("w:val"), "clear")
            sh.set(qn("w:fill"), "1F3A5F")
            c._tc.get_or_add_tcPr().append(sh)
        for row in rows:
            cells = t.add_row().cells
            for i, v in enumerate(row):
                cells[i].text = ""
                r = cells[i].paragraphs[0].add_run(str(v))
                r.font.size = Pt(9)
                r.bold = i == 0
        for i, w in enumerate(widths):
            t.columns[i].width = Inches(w)
            for row in t.rows:
                row.cells[i].width = Inches(w)
        h = OxmlElement("w:tblHeader")
        h.set(qn("w:val"), "true")
        t.rows[0]._tr.get_or_add_trPr().append(h)
        d.add_paragraph()

    d.add_heading("/dev/null command reference", 0)
    d.add_paragraph("Generated from data/commands.yaml by tools/gen_docs.py. Edit the YAML, not this file.")
    rule_of = {"actions": rules["actions"], "shop": rules["shop"], "people_actions": rules["people"]["people_actions"]}
    for n, (g, meta) in enumerate(cm["groups"].items(), 1):
        d.add_heading(f"{n}. {meta['title']}", 1)
        d.add_paragraph(meta["note"])
        rows = []
        for k, c in cm["commands"].items():
            if c["group"] != g:
                continue
            ef = ""
            r = c.get("rule", "")
            if r and "." not in r and r in rules["actions"]:
                ef = eff(rules["actions"][r].get("effects"))
            elif r.startswith("people_actions."):
                ef = ""
            rows.append([c["usage"] + (f"  (under {c['parent']})" if c.get("parent") else ""), cost_text(c), "yes" if c.get("online") else "",
                         when(c), need(c.get("needs")), ef, c["help"], ""])
        table(["Command", "Cost", "Online trail", "Appears when", "Needs to run", "Effects on your state", "What it does", "Your notes"],
              rows, [2.0, 0.8, 0.5, 1.4, 1.5, 1.7, 2.3, 0.9])
    d.add_heading("Research", 1)
    m = rules["research"]["methods"]
    table(["Method", "Hours", "Cost", "Skill xp", "Notes"],
          [[k, f"{v['hours']}h", f"${v['cost']}" if v["cost"] else "free", v["xp"],
            ("online trail" if v.get("online") else "no trail") + ("; reaches expert" if v.get("cap") == 3 else "")] for k, v in m.items()],
          [1.4, 0.8, 0.8, 0.8, 6.0])
    rows = [[k, t["blurb"], t["levels"][1]["gives"], t["levels"][2]["gives"], t["levels"][3]["gives"]]
            for k, t in rules["research"]["topics"].items()]
    table(["Topic", "About", "Level 1", "Level 2", "Level 3"], rows, [1.4, 2.8, 1.9, 1.9, 1.9])
    d.save(path)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=ROOT / "docs")
    args = ap.parse_args()
    rules = load_rules()
    args.out.mkdir(parents=True, exist_ok=True)
    make_txt(rules["commands"], args.out / "command_tree.txt")
    print(f"wrote {args.out / 'command_tree.txt'}")
    try:
        make_docx(rules, args.out / "command_reference.docx")
        print(f"wrote {args.out / 'command_reference.docx'}")
    except ImportError:
        print("skipped the .docx: install python-docx with  python -m pip install python-docx")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
