"""Generate the command tree and reference from data/commands/.

    python tools/gen_docs.py            writes docs/command_tree.txt
    python tools/gen_docs.py --out DIR  write somewhere else

Edit a file in data/commands/, run this, and the tree follows. Never edit the generated file.
The tree is drawn by tools/cmdtree.py, so the file you read and `cmdtree.cmd` always agree.
"""
from __future__ import annotations

import argparse
import contextlib
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from devnull.core.sim import DEFAULT_COMMANDS  # noqa: E402

sys.path.insert(0, str(ROOT / "tools"))
import cmdtree  # noqa: E402


def make_txt(path: Path) -> None:
    """The command tree (by group, then by gate), drawn by tools/cmdtree.py without colour."""
    cmdtree.USE_COLOR = False
    data = cmdtree.load(DEFAULT_COMMANDS)
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        for view in (cmdtree.view_group, cmdtree.view_needs):
            root, nodes = view(data, data["commands"], False)
            print(root)
            cmdtree.draw(nodes)
            print()
    head = "/dev/null COMMAND TREE (generated from data/commands/; do not edit this file)\n\n"
    path.write_text(head + buf.getvalue().replace(f"  ({DEFAULT_COMMANDS})", ""), encoding="utf-8", newline="\r\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=ROOT / "docs")
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    make_txt(args.out / "command_tree.txt")
    print(f"wrote {args.out / 'command_tree.txt'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
